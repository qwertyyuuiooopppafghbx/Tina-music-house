// Bundle this project's local modules into a classic script for file:// preview.
// Run after editing module sources: node tool/build.cjs
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const modules = new Map();
function visit(filename) {
  if (modules.has(filename)) return;
  const source = fs.readFileSync(filename, 'utf8');
  const exports = [...source.matchAll(/^export\s+(?:async\s+)?(?:function|const|let|var|class)\s+(\w+)/gm)].map(m => m[1]);
  const body = source.replace(/^import\s+(\* as \w+|\{[^}]+\})\s+from\s+['"]([^'"]+)['"];?\s*$/gm, (_, bindings, relative) => {
    const dependency = path.resolve(path.dirname(filename), relative);
    visit(dependency);
    const names = bindings.startsWith('* as ') ? bindings.slice(5) : bindings;
    return `const ${names} = modules[${JSON.stringify(dependency)}];`;
  }).replace(/^export\s+/gm, '');
  modules.set(filename, `modules[${JSON.stringify(filename)}] = (() => {\n${body}\nreturn { ${exports.join(', ')} };\n})();`);
}
visit(path.join(root, 'js/main.js'));
fs.writeFileSync(path.join(root, 'js/app.bundle.js'), '// Generated by tool/build.cjs. Edit source modules instead.\n(() => {\nconst modules = Object.create(null);\n' + [...modules.values()].join('\n') + '\n})();\n');
console.log(`Bundled ${modules.size} modules.`);
